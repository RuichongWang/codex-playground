#!/usr/bin/env bash
# 代码有多少行 —— **只报数,不判红。**
#
# 这里原来是 500 行硬顶。拿掉的理由:它防的是屎山,而行数只是屎山的一个粗劣代理,
# 它已经替我们做过一次错决定(「只剩 17 行,所以那个该加的检查先别加」)。
# 现在防屎山靠两样:tools/deps.py 查循环依赖(客观,无阈值),
# 以及一条由判官回答的条件「有没有哪个文件在同时干好几件不相干的事」。
# 这个数留着,是为了看趋势,不是为了拦人。
set -euo pipefail
N=$(cat done/*.py check.py | grep -v '^[[:space:]]*$' | grep -v '^[[:space:]]*#' | wc -l)
echo "实现代码 ${N} 行(只报数,不设上限)"
