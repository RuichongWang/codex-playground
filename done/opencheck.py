# -*- coding: utf-8 -*-
u"""开卡那一刻的额外体检:不是「这条判据合不合法」,是「这条判据写坏了没有」。

`card.validate` 管的是硬形状(四栏齐不齐、判者认不认得出、有没有一条命令答)。
这一份管的是**账上真栽过的那几种写坏**:

账上改过 14 次判据,其中 12 次是判据自己写坏了。12 次里机械查得动的有三种形状,
每一条检查后面都跟着它对应的那一次(编号是账上 amend 的序):

  A 问句和「过」对不上        ← 第 3 次(问句改了「过」没跟着改,一条该答「是」的按「否」算过)
                              ← 第 8 次(「有没有…」答「否」是个免费答案,改成「找出一个…」)
  B 人来答的找反例判据没交代怎么算搜过 ← 第 8 次(「没找到」必须写清搜了什么,不然照样是免费答案)
  C 审阅人的名字和给他的取材对不上   ← 第 7 次(只许看说明书的冷读者,对着「看这次改动」只能答「答不了」)
                                ← 第 10 次(那条看的是仓库当前状态,判者却叫「改动审阅人」,名不副实)
  E 开工前查库那一栏栏名自造    ← C-3 开卡时真发生过:数数的工具找的是「用上了」,
                                写的人写成了「捞到的[].怎么用」,于是那个数结构上永远是 0

**为什么「前移到开卡」只对这几种成立**(库里 C103 那条:核验前移的前提是判定不需要读
被保护的那套状态):这几种只看判据自己的文字就判得了,不需要知道那件活干成没有。
剩下 5 次(问句有歧义、范围写错这类)要读懂那件活才判得了 —— 前移是假的,所以不做。

还有一种形状(答案永远是同一个,第 10 · 12 · 13 次)机械拦不了,**只能落成读数** ——
见 `开卡实况`,它记不拦。
"""
import re

from done.ledger import Refused

# 「找出一个…」这类找反例的判据,通过的那边只能是「没找到」。
找反例 = re.compile(u"^\\s*找出")
是问句 = re.compile(u"[吗?？]\\s*$")

# 判者的名字里点了名要读什么,卡上「凭什么答」就得真把那样东西给他。
# 只管名字以「审阅人 / 读者」收尾的 —— 那是这个仓给「来读东西的人」起名的惯例;
# 「照说明书跑的人」是来干活的,不在这条管的范围里。
来读的 = re.compile(u"(审阅人|读者)$")
点名的取材 = (
    (u"改动", (u"改动", u"diff")),
    (u"说明书", (u"说明书", u"README", u"docs", u".md")),
    (u"库", (u"库", u"条目", u"catalog")),
    (u"代码", (u"代码", u"文件", u"done/", u"tools/", u".py")),
)

查库栏 = (u"查了什么", u"捞到的", u"用上了", u"没查到的", u"查了没有")


def 查判据(accept):
    u"""逐条查形状,返回一串抱怨(空 = 没毛病)。"""
    坏 = []
    for c in accept:
        cid, 问, 过 = c.get(u"id"), c.get(u"问") or u"", c.get(u"过")
        判者 = c.get(u"判者") or {}
        凭 = c.get(u"凭什么答") or u""
        if 找反例.match(问):
            if 过 != u"没找到":
                坏.append(u"%s 是「找出一个…」的问法,「过」只能是「没找到」,现在写的是「%s」 —— "
                          u"问句和怎么算过对不上,账上第 3 次改判据就栽在这儿" % (cid, 过))
            # 命令答的找反例判据不在此列:一次全量扫描就是最彻底的搜,退出码本身就是交代。
            if 判者.get(u"读者") and u"没找到" not in 凭:
                坏.append(u"%s 由人来答又是找反例,「凭什么答」里要交代一句"
                          u"「答没找到就写清什么」 —— 不交代的话「没找到」是个免费答案"
                          u"(账上第 8 次)" % cid)
        elif 是问句.search(问):
            if 过 not in (u"是", u"否"):
                坏.append(u"%s 是「…吗?」的问法,「过」只能是「是」或「否」,现在写的是「%s」" % (cid, 过))
        else:
            坏.append(u"%s 的「问」既不是「找出一个…」也不是「…吗?」—— "
                      u"答域不明,判的人不知道该答什么" % cid)
        谁 = 判者.get(u"读者") or u""
        if 来读的.search(谁):
            for 词, 线索 in 点名的取材:
                if 词 in 谁 and not any(x in 凭 for x in 线索):
                    坏.append(u"%s 的判者叫「%s」,名字里点了「%s」,可是「凭什么答」里"
                              u"一样这类东西都没给他(%s)—— 名字和取材对不上,"
                              u"他很可能只能答「答不了」(账上第 7 · 10 次)"
                              % (cid, 谁, 词, u" / ".join(线索)))
    return 坏


def 查查库(q):
    u"""开工前查库那一栏:栏名得是数数的工具认得的那几个。"""
    if not q:
        return []
    多出来 = [k for k in q if k not in 查库栏]
    坏 = []
    if 多出来:
        坏.append(u"查库那一栏有数数的工具不认得的栏名:%s —— 它认的是 %s"
                  % (u"、".join(多出来), u"、".join(查库栏)))
    if q.get(u"查了什么") and u"用上了" not in q:
        坏.append(u"查库记了「查了什么」却没有「用上了」这一栏 —— "
                  u"于是「查到并真用上」那个数结构上永远是 0(C-3 开卡时真这么错过一次)。"
                  u"一次都没用上就写「用上了」:「没有,都不对路」")
    return 坏


def 拦(accept, 查库=None):
    坏 = 查判据(accept) + 查查库(查库)
    if 坏:
        raise Refused(u"open-shape", u"这张卡的判据写坏了:\n  - " + u"\n  - ".join(坏))
    return True


def 开卡实况(accept, timeout=120):
    u"""开卡这一刻,把每条命令判据先跑一遍,记下它现在是什么颜色。

    **这一条记,不拦。** 它对的是账上第 10 · 12 · 13 次改判据 —— 那三次的毛病都是
    「这条判据的答案永远是同一个」,而恒绿的判据和不存在的判据在判决那一刻一模一样。
    这种毛病机械拦不住(体检卡就该一开卡全绿),但它能变成一个读数:
    开卡时是什么颜色、判决时是什么颜色,两边都记下来,常数就看得见了。
    """
    import subprocess
    出 = []
    for c in accept:
        cmd = (c.get(u"判者") or {}).get(u"cmd")
        if not cmd:
            continue
        try:
            p = subprocess.run(cmd, shell=True, timeout=timeout,
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            码 = p.returncode
        except Exception as e:
            码 = u"跑不起来:%s" % e
        出.append({u"id": c.get(u"id"), u"cmd": cmd, u"exit": 码,
                   u"开卡就绿": 码 == 0})
    return 出
